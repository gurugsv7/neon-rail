from playwright.sync_api import sync_playwright
import json,sys,time
sys.stdout.reconfigure(encoding='utf-8')
results=[]
def record(name,passed,detail=None):
    results.append(dict(test=name,passed=bool(passed),detail=detail))
    print(('PASS ' if passed else 'FAIL ')+name, json.dumps(detail) if detail else '',flush=True)
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True,args=['--enable-webgl','--ignore-gpu-blocklist'])
    page=browser.new_page(viewport={'width':1366,'height':768})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:errors.append(m.text) if m.type=='error' else None)
    page.goto('http://127.0.0.1:8765/NEON%20RAIL.html?qa',wait_until='networkidle')
    page.wait_for_function('!!window.__rail')
    page.evaluate('window.__rail.game.testClock=true')
    page.get_by_role('button',name='LET’S RUN').click()
    page.evaluate('window.__rail.game.audio.enabled=false')
    def ev(s):return page.evaluate(s)
    def snap():return ev('__rail.snapshot()')
    def advance(t):return ev(f'__rail.advance({t})')
    def reset():ev('__rail.game.start();__rail.clear();__rail.game.audio.enabled=false')
    reset()
    record('Run button enters gameplay',snap()['state']=='playing')
    page.keyboard.press('a');s=advance(.20)
    record('Left lane smoothly interpolates',s['player']['lane']==0 and -3.25<s['player']['x']<-3.17,s['player']['x'])
    for key in ['d','a','d','a','d','d','a','d']:page.keyboard.press(key);advance(.035)
    s=advance(.3)
    record('Rapid alternating switches and lane clamping',s['player']['lane']==2 and abs(s['player']['x']-3.25)<.02)
    page.keyboard.press('Space');s=advance(.48)
    record('Jump reaches a useful apex',2.8<s['player']['y']<3.1 and not s['player']['grounded'],s['player']['y'])
    page.keyboard.press('a');s=advance(.22)
    record('Airborne lane switch',s['player']['lane']==1 and abs(s['player']['x'])<.04 and s['player']['y']>2)
    s=advance(.6);record('Gravity and landing',s['player']['grounded'] and s['player']['y']==0)
    reset();ev('__rail.spawn("overhead",1,4)');page.keyboard.press('s');s=advance(.5)
    record('Slide clears overhead barrier',s['state']=='playing' and s['threat']==0 and s['player']['slide']>0)
    reset();ev('__rail.spawn("overhead",1,4)');s=advance(.5)
    record('Standing overhead collision causes stumble',s['state']=='playing' and s['threat']>0 and s['player']['stumble']>0)
    advance(1.5);ev('__rail.spawn("hurdle",1,3)');s=advance(1)
    record('Repeated mistakes trigger security capture',s['state']=='over')
    page.get_by_role('button',name='RUN AGAIN').click();record('Run-again button resets run',snap()['state']=='playing' and snap()['distance']==0)
    reset();ev('__rail.spawn("hurdle",1,7)');page.keyboard.press('Space');s=advance(.7)
    record('Jump clears hurdle without collision',s['state']=='playing' and s['threat']==0)
    reset();ev('__rail.spawn("train",1,14)');page.keyboard.press('Space');s=advance(.88)
    s=advance(1);record('Ground jump cannot bypass a full-height train',s['state']=='over')
    reset();ev('__rail.spawn("rampTrain",1,24)');s=advance(1.25)
    record('Ramp transitions onto full-height train roof',s['state']=='playing' and abs(s['player']['y']-4.27)<.01 and s['threat']==0,s['player'])
    s=advance(1.5);record('Fall from train roof and land',s['state']=='playing' and s['player']['grounded'] and s['player']['y']==0)
    reset();ev('__rail.spawn("cargo",1,9)');page.keyboard.press('Space');s=advance(.6)
    record('Cargo jump clearance',s['state']=='playing' and s['threat']==0)
    reset();ev('__rail.spawn("gap",1,8)');page.keyboard.press('Space');s=advance(1)
    record('Gap can be jumped',s['state']=='playing' and s['player']['fall']==0)
    reset();ev('__rail.spawn("gap",1,5)');s=advance(1)
    record('Missed gap produces fall and game over',s['state']=='over' and s['player']['fall']==1)
    reset();ev('__rail.spawn("train",1,10)');s=advance(1)
    record('Train frontal collision ends run',s['state']=='over')
    for power in ['shield','board']:
        reset();ev(f'__rail.power("{power}");__rail.spawn("train",1,10)');s=advance(1)
        record(power+' absorbs train collision',s['state']=='playing' and s['power'][power]==0 and s['player']['invincible']>0)
    reset();ev('__rail.game.world.addToken(1,__rail.game.distance+3,1.05)');s=advance(.3)
    record('Token pickup updates score and counter',s['tokens']==1 and s['score']>10)
    reset();ev('__rail.power("magnet");__rail.game.world.addToken(0,__rail.game.distance+8,1.05);__rail.game.world.addToken(2,__rail.game.distance+9,1.05)');s=advance(.8)
    record('Magnet collects from both adjacent lanes',s['tokens']==2,s['tokens'])
    reset();ev('__rail.game.multiplier=1');normal=advance(1)['score'];reset();ev('__rail.game.multiplier=1;__rail.power("boost")');boost=advance(1)['score']
    record('Score boost doubles distance score',abs(boost/normal-2)<.01,{'normal':normal,'boost':boost})
    for power in ['magnet','boost','shield','board']:
        reset();ev(f'void __rail.game.world.addPower("{power}",1,3)');s=advance(.3)
        record(power+' 3D pickup activates timer',s['power'][power]>0)
        ev(f'__rail.game.power.{power}=.1');s=advance(.2)
        record(power+' expires',s['power'][power]==0)
    reset();ev('__rail.spawn("approach",0,30);__rail.spawn("depart",2,30)');advance(.5)
    positions=ev('__rail.game.world.entities.map(e=>({type:e.type,delta:e.s-e.baseS,warned:e.warned}))')
    record('Trains move in both directions with inbound warning',positions[0]['delta']<0 and positions[1]['delta']>0 and positions[0]['warned'],positions)
    reset();advance(1);page.keyboard.press('Escape');before=snap();advance(3);after=snap()
    record('Pause freezes distance and powers',before['state']=='paused' and after['distance']==before['distance'])
    page.get_by_role('button',name='KEEP RUNNING').click();s=advance(.5);record('Resume button continues run',s['state']=='playing' and s['distance']>before['distance'])
    page.keyboard.press('Escape');page.get_by_role('button',name='RESTART RUN').click();record('Pause restart resets distance',snap()['distance']==0 and snap()['state']=='playing')
    page.keyboard.press('Escape');page.get_by_role('button',name='MAIN MENU',exact=True).click();record('Quit to main menu',snap()['state']=='menu')
    reset();ev('__rail.game.score=123456;__rail.game.end()');stored=ev('JSON.parse(localStorage.getItem("neon-rail-v1")).best')
    page.reload(wait_until='networkidle');page.wait_for_function('!!window.__rail');record('Best score survives reload',stored==123456 and snap()['best']==123456)
    ev('__rail.game.testClock=true');reset();ev('__rail.game.save.data.totalTokens=99;__rail.game.completed.delete("totalTokens");__rail.game.stat("totalTokens",1)')
    record('Mission completion increases multiplier',ev('__rail.game.completed.has("totalTokens")') and snap()['multiplier']>=2)
    # A real movement controller follows the guaranteed corridor; collision
    # detection stays enabled and no invulnerability is used.
    ev('''window.runSoak=(seconds)=>{const g=__rail.game;const dt=1/120;let peakEntities=0,peakTokens=0;for(let i=0;i<seconds*120;i++){
      let closest=null;for(const e of g.world.entities){if(e.baseS+22>g.distance&&(!closest||e.baseS<closest.baseS))closest=e;}
      if(closest){const row=g.world.entities.filter(e=>Math.abs(e.baseS-closest.baseS)<.01);const safe=[0,1,2].find(l=>!row.some(e=>e.lane===l));if(safe!==undefined&&safe!==g.player.lane)g.player.move(Math.sign(safe-g.player.lane));}
      g.step(dt);if(g.state!=='playing')return {failed:true,at:g.distance,player:{...g.player},hazards:g.world.entities.map(e=>({type:e.type,lane:e.lane,z:e.s-g.distance}))};
      if(i%120===0){g.render(1/60);peakEntities=Math.max(peakEntities,g.world.entities.length);peakTokens=Math.max(peakTokens,g.world.tokens.length);}
    }return {...g.snapshot(),peakEntities,peakTokens};}''')
    ev('__rail.game.start();__rail.game.audio.enabled=false;__rail.game.save.data.totalTokens=200;__rail.game.multiplier=1')
    checkpoints=[]
    for i in range(6):
        s=ev('runSoak(120)');checkpoints.append(s);print('SOAK',i+1,json.dumps(s),flush=True)
        if s.get('failed'):break
    record('12-minute traversable generated run with real collisions',len(checkpoints)==6 and not s.get('failed') and s.get('state')=='playing',{'distance':s.get('distance'),'patterns':s.get('generated'),'speed':s.get('speed')})
    record('Bounded entity and token counts',not s.get('failed') and all(c.get('peakEntities',999)<30 and c.get('peakTokens',999)<250 for c in checkpoints))
    record('Geometry and texture counts stabilize',not s.get('failed') and max(c['geometries'] for c in checkpoints[2:])-min(c['geometries'] for c in checkpoints[2:])<5 and len(set(c['textures'] for c in checkpoints[2:]))==1,[{'geometries':c.get('geometries'),'textures':c.get('textures')} for c in checkpoints])
    for width,height in [(1366,768),(1920,1080),(2560,1440)]:
        page.set_viewport_size({'width':width,'height':height});page.wait_for_timeout(200)
        size=ev('({w:__rail.game.renderer.domElement.clientWidth,h:__rail.game.renderer.domElement.clientHeight,aspect:__rail.game.camera.aspect})')
        record(f'Resize {width}x{height}',size['w']==width and size['h']==height and abs(size['aspect']-width/height)<.001)
    page.set_viewport_size({'width':1440,'height':900})
    ev('__rail.game.menu()');page.wait_for_timeout(1600);page.screenshot(path='work/final-menu.png')
    reset();ev('__rail.game.world.addEntity("train",0,18);__rail.game.world.addEntity("overhead",2,37);__rail.game.world.addEntity("rampTrain",1,60);for(let i=0;i<15;i++)__rail.game.world.addToken(1,5+i*3);__rail.game.world.step(0,__rail.game);__rail.game.time=8');page.wait_for_timeout(1200);page.screenshot(path='work/final-gameplay.png')
    record('No browser console or runtime errors',len(errors)==0,errors)
    # Actual animation performance; headless measurements are environment-specific.
    ev('__rail.game.testClock=false;window.frameTimes=[];window.lastFrame=performance.now();window.sampleFrame=t=>{frameTimes.push(t-lastFrame);lastFrame=t;if(frameTimes.length<180)requestAnimationFrame(sampleFrame)};requestAnimationFrame(sampleFrame)')
    page.wait_for_function('frameTimes.length>=180',timeout=180000)
    perf=ev('({average:frameTimes.reduce((a,b)=>a+b,0)/frameTimes.length,frames:frameTimes.length,renderer:__rail.game.renderer.capabilities.maxTextures})')
    print('PERFORMANCE',perf,flush=True)
    json.dump({'results':results,'soak':checkpoints,'performance':perf,'errors':errors},open('work/test-results.json','w'),indent=2)
    browser.close()
if any(not r['passed'] for r in results):sys.exit(1)
